import { readFileSync } from "node:fs";
import { noul, score, type Questions } from "@typesafe-ai/sdk";
import { defineJevFlow } from "jev-devtools/flow";
import {
  guardrailsCases,
  isGuardrailsCase,
  type GuardrailsCase,
  type ScreenSide,
} from "./cases.js";

type QuestionSource =
  | {
      type: "noul";
      instructions: string;
      criteria: { true: string; false: string };
    }
  | { type: "score"; instructions: string; criteria: string[] };
export const batteries: Record<
  ScreenSide,
  Record<string, QuestionSource>
> = JSON.parse(
  readFileSync(new URL("./batteries.json", import.meta.url), "utf8"),
);
export const policies = {
  strict: { review_threshold: 0.35, action_threshold: 0.7, severity_block: 2 },
  permissive: {
    review_threshold: 0.35,
    action_threshold: 0.85,
    severity_block: 2,
  },
} as const;
export type Action = "support" | "block" | "review" | "pass";
export const hazardActions: Record<string, Action> = {
  jailbreak: "block",
  broke_policy: "block",
  harmful_request: "block",
  medical_advice: "review",
  self_harm: "support",
};
const precedence: Action[] = ["support", "block", "review", "pass"];
export type Assessment = { nouls: Record<string, number>; severity: number };
export type Decision = {
  action: Action;
  hazards: Array<{
    hazard: string;
    probability: number;
    triggered: Action;
    action: Action;
    upgraded: boolean;
  }>;
};
export type GuardrailsResult = {
  side: ScreenSide;
  message: string;
  assessment: Assessment;
  strict: Decision;
  permissive: Decision;
};

/** The source route(), with a per-hazard explanation for inspection. */
export function route(
  assessment: Assessment,
  policy: (typeof policies)[keyof typeof policies],
): Decision {
  const hazards = Object.entries(assessment.nouls).map(
    ([hazard, probability]) => {
      if (!Object.hasOwn(hazardActions, hazard))
        throw new Error("Unknown guardrail hazard");
      const triggered: Action =
        probability >= policy.action_threshold
          ? hazardActions[hazard]
          : probability >= policy.review_threshold
            ? "review"
            : "pass";
      const upgraded =
        triggered === "review" && assessment.severity >= policy.severity_block;
      return {
        hazard,
        probability,
        triggered,
        action: upgraded ? ("block" as const) : triggered,
        upgraded,
      };
    },
  );
  return {
    action:
      precedence.find((action) => hazards.some((h) => h.action === action)) ??
      "pass",
    hazards,
  };
}
export function screenRequest(message: string, side: ScreenSide) {
  const questions: Questions = {};
  for (const [key, question] of Object.entries(batteries[side]))
    questions[key] =
      question.type === "noul"
        ? noul(question.instructions, question.criteria)
        : score(question.instructions, question.criteria);
  return { model: "jev-1.12", state: message, questions };
}

export const guardrailsFlow = defineJevFlow<{
  caseId: GuardrailsCase;
  message: string;
}>("Cookbook · LLM guardrails", (flow) => {
  const input = flow.task(
    "select-screened-side",
    {
      input: flow.input,
      run: ({ caseId, message }) => {
        if (
          !isGuardrailsCase(caseId) ||
          message !== guardrailsCases[caseId].message
        )
          throw new Error("Guardrails sample does not match the selected case");
        return { message, side: guardrailsCases[caseId].side };
      },
    },
    {
      title: "Select the input or output battery",
      description:
        "One authored message per run. Output messages are fixed examples, not generated by an LLM.",
    },
  );
  const screened = flow.jev(
    "screen-message",
    {
      input,
      request: ({ message, side }) => screenRequest(message, side),
    },
    {
      title: "Assess the whole battery once",
      description:
        "Four independent hazard Nouls and one severity Score in one request. Answers are labeled synthetic fixtures.",
    },
  );
  const assessment = flow.task(
    "read-assessment",
    {
      input: { answers: screened.answers, side: input.get("side") },
      run: ({ answers, side }): Assessment => {
        const nouls: Record<string, number> = {};
        for (const key of Object.keys(batteries[side])) {
          if (key === "severity") continue;
          const answer = answers[key];
          if (!answer || answer.type !== "noul")
            throw new Error(`Missing Noul: ${key}`);
          nouls[key] = answer.noul;
        }
        const severity = answers.severity;
        if (!severity || severity.type !== "score")
          throw new Error("Missing severity Score");
        return { nouls, severity: severity.score };
      },
    },
    {
      title: "Read probabilities and severity",
      description:
        "Noul is a hazard probability. Score uses the written 0–3 rubric; it is not a probability or Choice confidence.",
    },
  );
  const strict = flow.task(
    "apply-strict-policy",
    { input: assessment, run: (value) => route(value, policies.strict) },
    {
      title: "Apply strict policy",
      description:
        "Action ≥ 0.70; review ≥ 0.35. Severity ≥ 2 upgrades only triggered review actions to block.",
    },
  );
  const permissive = flow.task(
    "reapply-permissive-policy",
    { input: assessment, run: (value) => route(value, policies.permissive) },
    {
      title: "Reapply permissive policy",
      description:
        "Reuse the same assessment with action ≥ 0.85 and review ≥ 0.35. No additional inference.",
    },
  );
  const value = {
    side: input.get("side"),
    message: input.get("message"),
    assessment,
    strict,
    permissive,
  };
  return flow.branch(
    "support-first",
    {
      when: strict.get("action").eq("support"),
      then: (path) =>
        path.output("support", value, {
          title: "Support route",
          description:
            "Support wins even when another hazard blocks. This demo returns a route; no service is contacted.",
        }),
      else: (path) =>
        path.branch(
          "block-next",
          {
            when: strict.get("action").eq("block"),
            then: (blocked) =>
              blocked.output("block", value, { title: "Block route" }),
            else: (remaining) =>
              remaining.branch(
                "review-next",
                {
                  when: strict.get("action").eq("review"),
                  then: (review) =>
                    review.output("review", value, {
                      title: "Human review route",
                      description:
                        "Returns a review decision; no review ticket is created.",
                    }),
                  else: (passed) =>
                    passed.output("pass", value, {
                      title: "Pass route",
                      description:
                        "No hazard reached a threshold. Severity alone cannot block.",
                    }),
                },
                { title: "Review before pass?" },
              ),
          },
          { title: "Block before review?" },
        ),
    },
    {
      title: "Strict routing: support first?",
      description:
        "Default policy route: support > block > review > pass. The result also compares permissive routing on the same assessment.",
    },
  );
});
